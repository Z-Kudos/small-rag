#!/bin/sh
set -eu

# 仅监听回环地址，避免 Qdrant 被容器外访问；对外只暴露应用的 18080。
export QDRANT__SERVICE__HOST="${QDRANT_BIND_HOST:-127.0.0.1}"
export QDRANT__SERVICE__HTTP_PORT="${QDRANT_HTTP_PORT:-6333}"
export QDRANT__SERVICE__GRPC_PORT="${QDRANT_GRPC_PORT:-6334}"
export QDRANT__STORAGE__STORAGE_PATH="${QDRANT_STORAGE_PATH:-/data/qdrant/storage}"
export QDRANT__TELEMETRY_DISABLED=true

# 单容器内存优化：限制 Qdrant 常驻内存占比与后台线程数（单机单节点，无需高并发 worker）。
# 这些值可用部署环境的同名变量覆盖。
export QDRANT__STORAGE__QUOTAS__ENABLED="${QDRANT_MEMORY_QUOTA_ENABLED:-true}"
export QDRANT__STORAGE__QUOTAS__MAX_RESIDENT_MEMORY_PERCENT="${QDRANT_MAX_RESIDENT_MEMORY_PERCENT:-60}"
export QDRANT__STORAGE__PERFORMANCE__MAX_SEARCH_THREADS="${QDRANT_MAX_SEARCH_THREADS:-2}"
export QDRANT__STORAGE__OPTIMIZERS__MAX_OPTIMIZATION_THREADS="${QDRANT_MAX_OPTIMIZATION_THREADS:-1}"
export QDRANT__STORAGE__HNSW_INDEX__MAX_INDEXING_THREADS="${QDRANT_MAX_INDEXING_THREADS:-2}"
export QDRANT__SERVICE__MAX_WORKERS="${QDRANT_MAX_WORKERS:-2}"

if [ -n "${QDRANT_API_KEY:-}" ]; then
    export QDRANT__SERVICE__API_KEY="${QDRANT_API_KEY}"
fi

exec /qdrant/qdrant --config-path /qdrant/config/config.yaml
